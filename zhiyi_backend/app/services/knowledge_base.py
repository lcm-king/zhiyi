def _expand_symptoms(text: str) -> set[str]:
    """使用同义词表扩展症状关键词，提升口语化描述召回率。"""
    tokens = _tokenize_chinese(text)
    expanded = set(tokens)
    for canonical, variants in SYMPTOM_SYNONYMS.items():
        for variant in variants:
            if variant in text or variant in tokens:
                expanded.add(canonical)
                expanded.update(variants)
                break
    return expanded


def _apply_direct_rules(symptoms: str, scored: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """应用症状组合直接规则，给明确疾病组合大幅加分。

    规则触发条件：所有 required 症状均命中（AND），且未被否定。
    """
    expanded = _expand_symptoms(symptoms)
    negated = _detect_negations(symptoms)
    scored_by_id = {item["id"]: item for item in scored}

    for rule in DIRECT_SYMPTOM_RULES:
        required = rule["required"]
        # 所有必须症状都需命中
        required_hits = [r for r in required if r in expanded]
        if len(required_hits) < len(required):
            continue
        # 如果任一必须症状被否定，跳过
        if any(neg in required_hits for neg in negated):
            continue

        optional_hits = [o for o in rule.get("optional", []) if o in expanded]
        boost = rule["boost"] + len(required_hits) * 5 + len(optional_hits) * 3

        disease_id = rule["disease_id"]
        if disease_id in scored_by_id:
            item = scored_by_id[disease_id]
            item["match_score"] = min(100, item["match_score"] + boost)
            item["raw_score"] = item.get("raw_score", item["match_score"]) + boost
            item["matched_keywords"].append(f"规则命中:{rule['name']}")
            item["matched_keywords"] = list(set(item["matched_keywords"]))

    return list(scored_by_id.values())


